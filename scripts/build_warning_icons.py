QUESTION = ["###.", "...#", ".##.", ".#..", "....", ".#.."]


def grid(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16, f"{len(rows)} rows"
    return [[c == "#" for c in r.ljust(16, ".")[:16]] for r in rows]


def slash(g):
    """Cut a 2-pixel diagonal through an icon, with a 1-pixel gap either side so it reads at 16 px."""
    g = [row[:] for row in g]
    for i in range(16):
        for d in (-1, 2):
            if 0 <= i + d < 16:
                g[i][i + d] = False
        for d in (0, 1):
            if i + d < 16:
                g[i][i + d] = True
    return g


def ghost_with_question(g):
    out = [[v and (x + y) % 2 == 0 for x, v in enumerate(row)] for y, row in enumerate(g)]
    for y, row in enumerate(QUESTION):
        for x, c in enumerate(row):
            out[y][12 + x] = c == "#"
    return out


def path(g):
    d = []
    for y, row in enumerate(g):
        x = 0
        while x < 16:
            if row[x]:
                start = x
                while x < 16 and row[x]:
                    x += 1
                d.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    return "".join(d)


def main():
    icons = {name: grid(art) for name, art in ART.items()}
    icons["racon-off"] = slash(icons["racon"])
    icons["dgnss-off"] = slash(icons["dgnss"])
    icons["light-off"] = slash(icons["light-off"])
    icons["buoy-missing"] = ghost_with_question(icons["buoy"])
    paths = {name: path(g) for name, g in sorted(icons.items())}
    symbols = "".join(f'<symbol id="w-{n}" viewBox="0 0 16 16"><path d="{d}"/></symbol>' for n, d in paths.items())
    (ROOT / "web" / "warning-icons.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" fill="currentColor" shape-rendering="crispEdges">'
        f"<!-- Pixel icons for navigational warnings, Lighthouses of India (scripts/build_warning_icons.py) -->{symbols}</svg>\n")
    (ROOT / "web" / "data" / "warning_icons.json").write_text(json.dumps(paths, separators=(",", ":")))
    print(f"{len(paths)} icons: {', '.join(paths)}")


if __name__ == "__main__":
    main()
